from __future__ import annotations

import os
import re
from enum import StrEnum
from pathlib import Path, PurePosixPath

import pathspec


class Classification(StrEnum):
    source = "source"
    config = "config"
    test = "test"
    docs = "docs"
    generated = "generated"
    vendored = "vendored"
    data = "data"
    binary = "binary"


