FILENAME_MAP: dict[str, str] = {
    "Dockerfile": "dockerfile", "Makefile": "make", "Jenkinsfile": "groovy",
    "Gemfile": "ruby", "Rakefile": "ruby", ".env": "dotenv",
}

SHEBANG_MAP: dict[str, str] = {
    "python": "python", "python3": "python", "node": "javascript", "bash": "bash",
    "sh": "bash", "zsh": "bash", "ruby": "ruby", "perl": "perl",
}

CONFIG_LANGS = {"yaml", "json", "toml", "xml", "ini", "dotenv", "hcl"}
DOC_LANGS = {"markdown", "rst", "text"}
DATA_EXTS = {".csv", ".tsv", ".parquet", ".sqlite", ".db", ".xlsx", ".xls", ".pkl",
             ".npy", ".jsonl", ".avro", ".feather"}
MANIFEST_NAMES = {
    "package.json", "pyproject.toml", "setup.py", "setup.cfg", "requirements.txt",
    "Pipfile", "go.mod", "Cargo.toml", "pom.xml", "build.gradle", "build.gradle.kts",
    "composer.json", "Gemfile", "tsconfig.json", ".editorconfig", ".prettierrc",
}

VENDORED_DIRS = {"node_modules", "vendor", "venv", ".venv", "site-packages",
                 "bower_components", "third_party", "Pods", ".tox"}
BUILD_DIRS = {"dist", "build", "target", "out", ".next", "__pycache__", ".pytest_cache",
              ".mypy_cache", ".ruff_cache", "obj", ".gradle", "coverage"}
# Not "bin": in Go, Ruby, and shell projects it holds source scripts; compiled files in it are
# already classified as binary.
# Build output and tool reports that are often committed by mistake: dist variants
# (dist-headless, dist_prod), test and coverage reports, framework caches.
BUILD_DIR_RE = re.compile(
    r"^(?:dist[-_.]\w[\w.-]*|playwright-report[\w.-]*|test-results|storybook-static|htmlcov"
    r"|\.turbo|\.vercel|\.svelte-kit|\.nuxt|\.output|\.parcel-cache|\.angular|\.docusaurus)$")
# Tool caches: metadata a tool derived from the source and tests (pytest node ids, type
# stubs, compiler caches), never shipped. A subset of the build directories above; unlike
# dist/ or .next/, which are shipped code, a credential in a cache is a copy of one elsewhere.
TOOL_CACHE_DIRS = {"__pycache__", ".pytest_cache", ".mypy_cache", ".ruff_cache", ".gradle",
                   ".parcel-cache", ".angular"}
LOCKFILES = {"package-lock.json", "yarn.lock", "pnpm-lock.yaml", "poetry.lock", "uv.lock",
             "Cargo.lock", "go.sum", "Gemfile.lock", "composer.lock", "Pipfile.lock",
             "bun.lockb", "flake.lock"}

TEST_DIRS = {"test", "tests", "__tests__", "spec", "specs", "testing"}


def is_dependency_or_build_dir(rel: PurePosixPath) -> bool:
    """True when the inventory excludes everything under the directory `rel` (relative to the
    source root) as vendored code or build output: the rule `reason` applies, per directory."""
    parts = rel.parts
    if not parts:
        return False
    if parts[-1] in VENDORED_DIRS:
        return True
    if any(part in TEST_DIRS for part in parts[:-1]):
        return False  # tests/build/ holds fixtures, not build output
    return parts[-1] in BUILD_DIRS or bool(BUILD_DIR_RE.match(parts[-1]))


TEST_FILE_RE = re.compile(
    r"(^test_.*\.py$)|(_test\.(py|go|rs|rb|ts|js)$)|(\.(test|spec)\.(ts|tsx|js|jsx|mjs)$)"
    r"|(Tests?\.(java|kt|cs|swift|scala)$)|(_spec\.rb$)|(^conftest\.py$)"
)
GENERATED_MARKERS = (b"@generated", b"DO NOT EDIT", b"Code generated by", b"auto-generated",
                     b"Autogenerated", b"automatically generated")
GENERATED_NAME_RE = re.compile(r"(\.min\.(js|css)$)|(\.pb\.go$)|(_pb2(_grpc)?\.py$)|(\.g\.dart$)")


def is_binary(sample: bytes) -> bool:
    return b"\0" in sample[:8000]


def detect_language(relpath: PurePosixPath, sample: bytes) -> str | None:
    name = relpath.name
    if name in FILENAME_MAP:
        return FILENAME_MAP[name]
    lang = EXTENSION_MAP.get(relpath.suffix) or EXTENSION_MAP.get(relpath.suffix.lower())
    if lang:
        return lang
    if sample.startswith(b"#!"):
        first = sample.split(b"\n", 1)[0].decode("utf-8", errors="replace")
        token = first.split()[-1].rsplit("/", 1)[-1] if first.split() else ""
        return SHEBANG_MAP.get(token)
    return None


def classify(relpath: PurePosixPath, language: str | None, sample: bytes) -> Classification:
    parts = relpath.parts
    name = relpath.name
    if is_binary(sample):
        return Classification.binary
    if any(p in VENDORED_DIRS for p in parts[:-1]):
        return Classification.vendored
    if GENERATED_NAME_RE.search(name) or any(m in sample[:1024] for m in GENERATED_MARKERS):
        return Classification.generated
    if any(p in TEST_DIRS for p in parts[:-1]) or TEST_FILE_RE.search(name):
        return Classification.test
    if name in MANIFEST_NAMES or (name.startswith("requirements") and name.endswith(".txt")):
        return Classification.config
    if language in DOC_LANGS or "docs" in parts[:-1] or "doc" in parts[:-1]:
        return Classification.docs
    if language in CONFIG_LANGS or name.startswith("."):
        return Classification.config
    if relpath.suffix.lower() in DATA_EXTS:
        return Classification.data
    if language is not None:
        return Classification.source
    return Classification.data


def build_output_dir(relpath: PurePosixPath) -> str | None:
    """The build-output or tool-cache directory (BUILD_DIRS, BUILD_DIR_RE) this file sits
    under, or None. A test directory above it wins: tests/build/fixture.py is a fixture."""
    for part in relpath.parts[:-1]:
        if part in TEST_DIRS:
            return None
        if part in BUILD_DIRS or BUILD_DIR_RE.match(part):
            return part
    return None


def tool_cache_dir(relpath: PurePosixPath) -> str | None:
    """The tool cache (TOOL_CACHE_DIRS) this file sits under, or None. Unlike build output, a
    test directory above it does not matter: tests/.pytest_cache is still pytest's cache."""
    return next((p for p in relpath.parts[:-1] if p in TOOL_CACHE_DIRS), None)


class Excluder:
    """Decides whether a file is excluded from analysis, and why.

    `tracked` holds the paths (posix, relative to `source_root`) in the tool's git index, or
    is None when there is no index to consult (a --files pile). Git never ignores a tracked
    file, so a .gitignore rule never excludes one (UNVAR-28)."""

    def __init__(self, source_root: Path, tracked: set[str] | None = None) -> None:
        self._tracked = tracked or set()
        # Every .gitignore applies to its own directory and below, as git applies them.
        self._specs: list[tuple[str, pathspec.GitIgnoreSpec]] = []
        if source_root.exists():
            for dirpath, dirnames, filenames in os.walk(source_root):
                dirnames[:] = sorted(d for d in dirnames
                                     if d != ".git" and d not in VENDORED_DIRS)
                if ".gitignore" not in filenames:
                    continue
                path = Path(dirpath) / ".gitignore"
                lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
                base = Path(dirpath).relative_to(source_root).as_posix()
                self._specs.append(("" if base == "." else base + "/",
                                    pathspec.GitIgnoreSpec.from_lines(lines)))

    def _ignored(self, rel: str) -> bool:
        return any(rel.startswith(base) and spec.match_file(rel[len(base):])
                   for base, spec in self._specs)

    def tracked_despite_gitignore(self, relpath: PurePosixPath) -> bool:
        rel = relpath.as_posix()
        return rel in self._tracked and self._ignored(rel)

    def reason(self, relpath: PurePosixPath) -> str | None:
        rel = relpath.as_posix()
        if rel not in self._tracked and self._ignored(rel):
            return "gitignore"
        for part in relpath.parts[:-1]:
            if part in VENDORED_DIRS:
                return f"vendored:{part}"
        build = build_output_dir(relpath)
        if build:
            return f"build_output:{build}"
        if relpath.name in LOCKFILES:
            return "lockfile"
        return None
